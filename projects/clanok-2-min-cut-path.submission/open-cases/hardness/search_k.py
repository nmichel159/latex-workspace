"""Search for DC pairs whose path-containing minimum cuts need many generators (theory-hardness.md, Section 6).

For a minimum u-v cut A (u side) let down(x) be the smallest minimum cut containing x and up(y) the largest one
avoiding y.  Every minimum cut is the union of A_min and the sets down(x), x in A (and the intersection of A_max and
the sets up(y), y not in A).  gen(A) = min(number of inclusion-maximal sets down(x), x in A - A_min;
number of inclusion-minimal sets up(y), y in A_max - A); gen(A) <= 1 means A is "single-generated".
k*(u,v) = min gen(A) over the minimum cuts A that contain a u-v path.  If k* were bounded by a constant k on DC,
testing all cuts generated by at most k vertices (O(n^k) cuts) would decide PATH-IN-MIN-CUT on DC.

Hill climbing over graphs with n vertices in DC (edge flips); score = 1000 * k* + number of minimum cuts.
Usage: python search_k.py n iterations seeds mode(dc|any).  Output: appended to results-k.txt.
"""

import os
import random
import sys
import time
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.normpath(os.path.join(HERE, "..", "..", "checks")))

import mcp  # noqa: E402
import exact as ex  # noqa: E402


def gen_number(n, cuts, A):
    amin = min(cuts, key=len)
    amax = max(cuts, key=len)
    downs = set()
    for x in A - amin:
        downs.add(min((B for B in cuts if x in B), key=len))
    downs = [D for D in downs if not any(D < E for E in downs)]
    ups = set()
    for y in amax - A:
        ups.add(max((B for B in cuts if y not in B), key=len))
    ups = [U for U in ups if not any(U > W for W in ups)]
    return min(len(downs), len(ups))


def analyse(n, es, need_dc):
    g = ex.UG(n, es)
    if not all(d is not None for d in ex.bfs_dist(g, 0)):
        return None
    if need_dc and not mcp.in_dc(mcp.Gr(n, es))[0]:
        return None
    best = (0, None)
    for u in range(n):
        du = ex.bfs_dist(g, u)
        for v in range(n):
            if v == u or du[v] != 2:
                continue
            if ex.cut_value(g, u, v, limit=3) < 3:
                continue
            try:
                c, cuts = ex.min_cuts_pq(g, u, v, max_free_classes=14)
            except ValueError:
                continue
            good = [A for A in cuts if ex.cut_graph_path(g, A, u, v) is not None]
            if not good:
                continue
            k = min(gen_number(n, cuts, A) for A in good)
            score = 1000 * k + len(cuts)
            if score > best[0]:
                best = (score, (u, v, c, len(cuts), len(good), k))
    return best


def climb(args):
    n, iters, seed, need_dc = args
    rng = random.Random(seed)
    allpairs = [(a, b) for a in range(n) for b in range(a + 1, n)]
    while True:
        es = set(p for p in allpairs if rng.random() < 0.4)
        r = analyse(n, sorted(es), need_dc)
        if r is not None:
            break
    cur, cur_score, cur_info = es, r[0], r[1]
    for it in range(iters):
        new = set(cur)
        for _ in range(rng.randint(1, 2)):
            new ^= {rng.choice(allpairs)}
        r = analyse(n, sorted(new), need_dc)
        if r is None:
            continue
        if r[0] >= cur_score or rng.random() < 0.02:
            cur, cur_score, cur_info = new, r[0], r[1]
    return seed, cur_score, cur_info, sorted(cur)


def main():
    n, iters, seeds, mode = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
    t0 = time.time()
    with Pool(30) as pool:
        res = pool.map(climb, [(n, iters, s, mode == "dc") for s in range(seeds)])
    res.sort(key=lambda t: -t[1])
    lines = ["search_k.py n=%d iterations=%d seeds=%d mode=%s" % (n, iters, seeds, mode)]
    ks = {}
    for seed, sc, info, es in res:
        k = info[5] if info else None
        ks[k] = ks.get(k, 0) + 1
    lines.append("  final k* over seeds: %s" % sorted(ks.items(), key=lambda t: (t[0] is None, t[0])))
    for seed, sc, info, es in res[:3]:
        lines.append("  seed %d score %d (u, v, c, #cuts, #cuts with path, k*) = %s; edges %s"
                     % (seed, sc, info, " ".join("%d-%d" % e for e in es)))
    lines.append("  Time %.0f s." % (time.time() - t0))
    with open(os.path.join(HERE, "results-k.txt"), "a") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
