"""Hub family without ties: the classes of hubties_min.py replaced by strict order relations.

Elements: bottoms (equivalent to u; with strict=True strictly between u and everything else), entry elements
eps_i, exit elements xi_j, route elements rA(i,j), rB(i,j), tops (equivalent to v; with strict=True strictly
between everything else and v).  Order generated by: bottoms < everything middle < tops, eps_i < rA(i,j) for all j,
xi_j < rB(i,j) for all i.  Real edges: fixed bottom-top edges of the nodes s, a, t; beta-r and r-top(n_p), r-top(n_{p+1})
for the routes of gadget p; a-eps_i, beta-eps_i; beta-xi_j, t-xi_j (t-side bottom of t).
"eps_i a peak" (hub entry used) forces rA(i, .) out of the down-set (eps_i < rA), so the route rA cannot be a valley.
Usage: python hubimp.py"""
import itertools
import time
import json
import zz
import pcfast


def hubimp(m, mp, order=None, strict=False, long=False):
    """strict=False: bottoms equivalent to u = bottom of s, tops equivalent to v = top of t (switch-model style).
    strict=True: a partial order (no two elements equivalent): u = bottom of s and v = top of t are the least and
    greatest elements, the other bottoms (a, beta, t) are pairwise incomparable and lie strictly between u and all
    middle elements, the other tops likewise below v; P2 for them through the added real edges u-bottom, top-v."""
    pairs = [(i, j) for i in range(m) for j in range(mp)] if order is None else list(order)
    nl = ["s"] + ["n%d" % p for p in range(1, len(pairs))] + ["a"]
    bots = [("bot", "s"), ("bot", "a"), ("bot", "beta"), ("bot", "t")]
    tops = [("top", x) for x in nl] + [("top", "t")]
    mids, R, less = [], [], []
    for p, (i, j) in enumerate(pairs):
        for kind, c in (("rA", i), ("rB", j)):
            r = (kind, i, j)
            mids.append(r)
            R += [(("bot", "beta"), r), (r, ("top", nl[p])), (r, ("top", nl[p + 1]))]
            less.append((("eps", c) if kind == "rA" else ("xi", c), r))
            if long:
                # a second, longer version of the same route: r1 - private top - r2 (simple paths of other lengths)
                r1, r2, x = (kind + "1", i, j), (kind + "2", i, j), ("top", "x%s%d%d" % (kind, i, j))
                mids += [r1, r2]
                tops.insert(len(tops) - 1, x)  # keep v = top of t last
                R += [(("bot", "beta"), r1), (r1, ("top", nl[p])), (r1, x),
                      (("bot", "beta"), r2), (r2, x), (r2, ("top", nl[p + 1]))]
                for rr in (r1, r2):
                    less.append((("eps", c) if kind == "rA" else ("xi", c), rr))
    for i in range(m):
        mids.append(("eps", i))
        R += [(("bot", "a"), ("eps", i)), (("bot", "beta"), ("eps", i))]
    for j in range(mp):
        mids.append(("xi", j))
        R += [(("bot", "beta"), ("xi", j)), (("bot", "t"), ("xi", j))]
    R += [(("bot", "s"), ("top", "s")), (("bot", "a"), ("top", "a")), (("bot", "t"), ("top", "t"))]
    names = bots + mids + tops
    n = len(names)
    idx = {x: i for i, x in enumerate(names)}
    u, v = idx[("bot", "s")], idx[("top", "t")]
    rel = set()
    for b in bots:
        for x in mids + tops:
            rel.add((idx[b], idx[x]))
    for x in mids:
        for tp in tops:
            rel.add((idx[x], idx[tp]))
    for a, b in less:
        rel.add((idx[a], idx[b]))
    if strict:
        for b in bots[1:]:
            rel.add((u, idx[b]))
            R.append((("bot", "s"), b))
        for tp in tops:
            if tp != ("top", "t"):
                rel.add((idx[tp], v))
                R.append((tp, ("top", "t")))
        lt = zz.closure(n, rel)
        return zz.ZZ(n, lt, [(idx[a], idx[b]) for a, b in R], u, v), names
    lt = zz.closure(n, rel)
    le = [[lt[a][b] or a == b for b in range(n)] for a in range(n)]
    for group in (bots, tops):
        for x in group:
            for y in group:
                le[idx[x]][idx[y]] = True
    for k in range(n):
        for i in range(n):
            if le[i][k]:
                for j in range(n):
                    if le[k][j]:
                        le[i][j] = True
    return zz.ZZ(n, None, [(idx[a], idx[b]) for a, b in R], u, v, le=le), names


def check(name, z):
    t0 = time.time()
    ex = zz.exact_dfs(z)[0]
    ex2 = zz.exact(z)[0] if z.n <= 26 else None
    p2bad = z.p2_bad()
    ac = zz.ac_answer(z)
    pc = pcfast.pc_answer(z) if ac else False
    flag = "  <-- PC FALSE POSITIVE" if (pc and not ex) else ""
    print("%-40s n=%3d |R|=%3d P2=%-5s exact=%-5s exact2=%-5s AC=%-5s PC=%-5s %5.1fs%s"
          % (name, z.n, len(z.R), not p2bad, ex, ex2, ac, pc, time.time() - t0, flag), flush=True)
    return ex, pc, p2bad


if __name__ == "__main__":
    for strict in (False, True):
        for m, mp in [(1, 1), (1, 2), (2, 1), (2, 2), (2, 3)]:
            z, names = hubimp(m, mp, strict=strict)
            ex, pc, bad = check("hubimp m=%d m'=%d %s" % (m, mp, "strict" if strict else "bottom/top classes"), z)
            if bad:
                print("   P2 violations:", [(names[a], names[b]) for a, b in bad][:6])
            if pc and not ex:
                fn = "runs/pcfp-hubimp-%d%d-%s.json" % (m, mp, "strict" if strict else "classes")
                json.dump({"n": z.n, "le": [[int(x) for x in r] for r in z.le], "R": z.R, "u": z.u, "v": z.v,
                           "names": [str(x) for x in names]}, open(fn, "w"))
